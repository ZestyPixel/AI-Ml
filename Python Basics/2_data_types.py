#Different Data Types in Python

#String
name = "Umar"
print("Name:", name)
print()

#Integer
age = 25    
print("Age:", age)

#Float
height = 5.9
print("Height:", height)

#Boolean
is_student = True #This is in snake case. Camel case would be isStudent and Pascal case would be IsStudent.
print("Is Student:", is_student)

#In boolean every non zero value is True
print(bool(10))
print(bool(0))
